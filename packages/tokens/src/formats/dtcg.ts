import type { BrandTheme } from "../brands";
import { primitives } from "../primitives";
import type { ColorMode } from "../semantic/derive";
import { semanticColorRoles } from "../semantic/roles";
import { textStyles, type TextStyle } from "../semantic/text-styles";
import { bezier } from "./shared";

type Token = { $type: string; $value: unknown; $description?: string };
type Group = { [key: string]: Token | Group | string };

const dimension = (value: number) => ({ value, unit: "px" });

function group(
  type: string,
  values: Readonly<Record<string, unknown>>,
  map = (value: unknown) => value
) {
  return Object.fromEntries(
    Object.entries(values).map(([key, value]) => [key, { $type: type, $value: map(value) }])
  );
}

/**
 * The tokens of one brand and mode in the W3C Design Tokens Community Group format, read by
 * Figma variables, Tokens Studio and Style Dictionary. Text styles reference the scales.
 */
export function toDesignTokens(theme: BrandTheme, mode: ColorMode, highContrast = false): Group {
  const colors = highContrast ? theme.highContrast[mode] : theme.colors[mode];
  const { typography, motion } = primitives;
  return {
    $description: `${theme.name}, ${mode}${highContrast ? " high contrast" : ""}. Generated by @nativesmart/tokens.`,
    color: Object.fromEntries(
      semanticColorRoles.map((role) => [role, { $type: "color", $value: colors[role] }])
    ),
    palette: Object.fromEntries(
      Object.entries(theme.palette).map(([name, scale]) => [name, group("color", scale)])
    ),
    space: group("dimension", primitives.spacing, (value) => dimension(value as number)),
    radius: {
      ...group("dimension", primitives.radius, (value) => dimension(value as number)),
      ...Object.fromEntries(
        Object.entries(theme.shape).map(([usage, key]) => [
          usage,
          { $type: "dimension", $value: `{radius.${key}}` }
        ])
      )
    },
    font: group("fontFamily", theme.typography.fontFamily, (value) => [...(value as string[])]),
    fontSize: group("dimension", typography.fontSize, (value) => dimension(value as number)),
    fontWeight: group("fontWeight", typography.fontWeight, (value) => Number(value)),
    lineHeight: group("number", typography.leading),
    letterSpacing: group("dimension", typography.letterSpacing, (value) => ({
      value: value as number,
      unit: "em"
    })),
    duration: group("duration", motion.duration, (value) => ({
      value: value as number,
      unit: "ms"
    })),
    easing: group("cubicBezier", motion.easing, (value) => bezier(value as string)),
    controlHeight: group("dimension", primitives.sizing.control, (value) =>
      dimension(value as number)
    ),
    iconSize: group("dimension", primitives.sizing.icon, (value) => dimension(value as number)),
    elevation: Object.fromEntries(
      Object.entries(primitives.elevation).map(([level, layers]) => [
        level,
        {
          $type: "shadow",
          $value: layers.map((layer) => ({
            color: `${mode === "light" ? theme.shadowTint.light : theme.shadowTint.dark}${Math.round(
              Math.min(1, layer.alpha * (mode === "light" ? 1 : 3)) * 255
            )
              .toString(16)
              .padStart(2, "0")}`,
            offsetX: dimension(layer.x),
            offsetY: dimension(layer.y),
            blur: dimension(layer.blur),
            spread: dimension(layer.spread)
          }))
        }
      ])
    ),
    typography: Object.fromEntries(
      Object.entries(textStyles).map(([name, value]) => {
        const style = value as TextStyle;
        const relative = style.fluid?.leading ?? style.leading;
        return [
          name,
          {
            $type: "typography",
            $value: {
              fontFamily: `{font.${style.family}}`,
              fontSize: `{fontSize.${style.size}}`,
              fontWeight: `{fontWeight.${style.weight}}`,
              letterSpacing: `{letterSpacing.${style.tracking}}`,
              lineHeight: relative
                ? typography.leading[relative]
                : Math.round(
                    (typography.lineHeight[style.size] / typography.fontSize[style.size]) * 1000
                  ) / 1000
            },
            $description: style.description
          }
        ];
      })
    )
  };
}
