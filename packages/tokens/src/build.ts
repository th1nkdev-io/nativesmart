import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { brandThemes } from "./brands";
import { toCss } from "./css";
import { toCSharp, toXaml } from "./formats/csharp";
import { toDart } from "./formats/dart";
import { toDesignTokens } from "./formats/dtcg";
import { toKotlin } from "./formats/kotlin";
import { toSwift } from "./formats/swift";
import { primitives } from "./tokens";
import { themes } from "./themes";
import { validateTokens } from "./validate";

const currentDir = __dirname;
const packageRoot = resolve(currentDir, "..");

async function writeJson(path: string, data: unknown) {
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, `${JSON.stringify(data, null, 2)}\n`);
}

function dartMap(value: unknown): string {
  return JSON.stringify(value, null, 2)
    .replace(/"([^"]+)":/g, "'$1':")
    .replace(/"/g, "'");
}

async function main() {
  validateTokens();

  await writeJson(resolve(packageRoot, "dist/json/primitives.json"), primitives);
  await writeJson(resolve(packageRoot, "dist/json/themes.json"), themes);
  await writeJson(resolve(packageRoot, "dist/json/brands.json"), brandThemes);

  await mkdir(resolve(packageRoot, "dist/css"), { recursive: true });
  for (const theme of Object.values(brandThemes)) {
    await writeFile(resolve(packageRoot, `dist/css/${theme.id}.css`), toCss(theme));
  }

  for (const theme of Object.values(brandThemes)) {
    for (const mode of ["light", "dark"] as const) {
      await writeJson(
        resolve(packageRoot, `dist/dtcg/${theme.id}.${mode}.tokens.json`),
        toDesignTokens(theme, mode)
      );
      await writeJson(
        resolve(packageRoot, `dist/dtcg/${theme.id}.${mode}-hc.tokens.json`),
        toDesignTokens(theme, mode, true)
      );
    }
  }

  await mkdir(resolve(packageRoot, "dist/swift"), { recursive: true });
  await writeFile(resolve(packageRoot, "dist/swift/NativesmartTokens.swift"), toSwift());
  await mkdir(resolve(packageRoot, "dist/compose"), { recursive: true });
  await writeFile(resolve(packageRoot, "dist/compose/NativesmartTokens.kt"), toKotlin());

  await mkdir(resolve(packageRoot, "dist/maui"), { recursive: true });
  await writeFile(resolve(packageRoot, "dist/maui/NativesmartTokens.cs"), toCSharp());
  for (const theme of Object.values(brandThemes)) {
    for (const variant of ["light", "dark", "lightHighContrast", "darkHighContrast"] as const) {
      await writeFile(
        resolve(packageRoot, `dist/maui/${theme.id}.${variant}.xaml`),
        toXaml(theme, variant)
      );
    }
  }

  await mkdir(resolve(packageRoot, "dist/flutter"), { recursive: true });
  await writeFile(resolve(packageRoot, "dist/flutter/nativesmart_theme.g.dart"), toDart());
  await writeFile(
    resolve(packageRoot, "dist/flutter/nativesmart_tokens.g.dart"),
    [
      "// Generated by @nativesmart/tokens. Do not edit by hand.",
      "const nativesmartPrimitives = " + dartMap(primitives) + ";",
      "const nativesmartThemes = " + dartMap(themes) + ";",
      ""
    ].join("\n")
  );

  await mkdir(resolve(packageRoot, "dist/react-native"), { recursive: true });
  await writeFile(
    resolve(packageRoot, "dist/react-native/tokens.ts"),
    [
      "// Generated by @nativesmart/tokens. Do not edit by hand.",
      `export const primitives = ${JSON.stringify(primitives, null, 2)} as const;`,
      `export const themes = ${JSON.stringify(themes, null, 2)} as const;`,
      ""
    ].join("\n")
  );
  await writeFile(
    resolve(packageRoot, "dist/react-native/tokens.d.ts"),
    [
      "// Generated by @nativesmart/tokens. Do not edit by hand.",
      "export declare const primitives: typeof import('../index').primitives;",
      "export declare const themes: typeof import('../index').themes;",
      ""
    ].join("\n")
  );
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
