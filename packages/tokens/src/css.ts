function densityVariables(factor: number): Record<string, string> {
  return Object.fromEntries(
    entries(primitives.sizing.control).map(([key, value]) => [
      `${cssPrefix}-control-height-${key}`,
      px(Math.round((value * factor) / 2) * 2)
    ])
  );
}

/** CSS variable of a spacing step: `0.5` becomes `--ns-space-0-5`. */
export function spaceVariable(key: string | number) {
  return `${cssPrefix}-space-${String(key).replace(".", "-")}`;
}

/** Grows from `min` on a 375px screen to `max` on a 1440px screen. */
export function fluidSize(min: FontSizeKey, max: FontSizeKey) {
  const from = primitives.typography.fontSize[min];
  const to = primitives.typography.fontSize[max];
  const slope = (to - from) / (fluidRange.max - fluidRange.min);
  const base = from - slope * fluidRange.min;
  return `clamp(${px(from)}, ${base.toFixed(2)}px + ${(slope * 100).toFixed(3)}vw, ${px(to)})`;
}

function gridVariables(breakpoint: GridBreakpoint) {
  const { columns, gutter, margin } = primitives.grid[breakpoint];
  return {
    [`${cssPrefix}-grid-columns`]: String(columns),
    [`${cssPrefix}-grid-gutter`]: px(gutter),
    [`${cssPrefix}-grid-margin`]: px(margin)
  };
}

/** The grid changes at each breakpoint. */
function gridMediaQueries() {
  return entries(primitives.grid)
    .filter(([, value]) => value.minWidth > 0)
    .map(
      ([key, value]) =>
        `@media (min-width: ${value.minWidth}px) {\n${block(":root", gridVariables(key as GridBreakpoint)).replace(/^/gm, "  ")}\n}`
    );
}

function block(selector: string, variables: Record<string, string>) {
  const lines = Object.entries(variables).map(([name, value]) => `  ${name}: ${value};`);
  return `${selector} {\n${lines.join("\n")}\n}`;
}

function textStyleClasses() {
  return entries(textStyles).map(([name, style]) => {
    const prefix = `${cssPrefix}-text-${name}`;
    const rules = [
      `  font-family: var(${prefix}-family);`,
      `  font-size: var(${prefix}-size);`,
      `  line-height: var(${prefix}-line-height);`,
      `  font-weight: var(${prefix}-weight);`,
      `  letter-spacing: var(${prefix}-tracking);`
    ];
    const options = style as TextStyle;
    if (options.uppercase) rules.push("  text-transform: uppercase;");
    if (options.italic) rules.push("  font-style: italic;");
    if (options.tabular) rules.push("  font-variant-numeric: tabular-nums;");
    if (options.underline) {
      rules.push(
        "  text-decoration-line: underline;",
        `  text-decoration-thickness: var(${cssPrefix}-underline-thickness);`,
        `  text-underline-offset: var(${cssPrefix}-underline-offset);`
      );
    }
    return `.ns-text-${name} {\n${rules.join("\n")}\n}`;
  });
}

/**
 * Builds the stylesheet for one brand theme. Light mode applies to `:root`; dark mode applies
 * under a `.dark` class (Nuxt color-mode, Tailwind `darkMode: "class"`) or `data-ns-theme="dark"`.
 * Density applies with `data-ns-density="compact"` or `"spacious"`. Text styles are also exposed
 * as `.ns-text-<style>` classes.
 */
export function toCss(theme: BrandTheme) {
  const light = modeVariables(theme, "light");
  const dark = modeVariables(theme, "dark");

  return [
    `/* Generated by @nativesmart/tokens for the "${theme.id}" theme. Do not edit by hand. */`,
    block(":root", { ...foundationVariables(), ...brandVariables(theme), ...light }),
    block('[data-ns-theme="light"]', light),
    block('.dark,\n[data-ns-theme="dark"]', dark),
    block('[data-ns-theme="light-hc"]', modeVariables(theme, "light", true)),
    block('[data-ns-theme="dark-hc"]', modeVariables(theme, "dark", true)),
    block('[data-ns-density="compact"]', densityVariables(primitives.density.compact)),
    block('[data-ns-density="spacious"]', densityVariables(primitives.density.spacious)),
    ...gridMediaQueries(),
    ...textStyleClasses(),
    ...animationRules(),
    ...preferenceBlocks(),
    ""
  ].join("\n\n");
}

/**
 * Builds the brand-dependent variables of one theme for the elements matching `scope` only, for
 * example to preview an identity inside a page styled with another one. Foundation scales and
 * density stay inherited from the page; the color mode follows `.dark` or `data-ns-theme` on an
 * ancestor.
 */
export function toScopedCss(theme: BrandTheme, scope: string) {
  const light = modeVariables(theme, "light");
  const dark = modeVariables(theme, "dark");

  return [
    `/* "${theme.id}" theme scoped to ${scope}. */`,
    block(scope, { ...brandVariables(theme), ...light }),
    block(`[data-ns-theme="light"] ${scope}`, light),
    block(`.dark ${scope},\n[data-ns-theme="dark"] ${scope}`, dark),
    block(
      `${scope} [data-ns-theme="light-hc"],\n${scope}[data-ns-theme="light-hc"]`,
      modeVariables(theme, "light", true)
    ),
    block(
      `${scope} [data-ns-theme="dark-hc"],\n${scope}[data-ns-theme="dark-hc"]`,
      modeVariables(theme, "dark", true)
    ),
    ""
  ].join("\n\n");
}
