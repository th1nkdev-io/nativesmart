/** Every CSS custom property generated by Nativesmart starts with this prefix. */
export const cssPrefix = "--ns";

export function kebab(value: string) {
  return value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);
}

export function cssColorVariable(role: string) {
  return `${cssPrefix}-color-${kebab(role)}`;
}

function px(value: number) {
  return value === 0 ? "0" : `${value}px`;
}

function fontStack(stack: FontStack) {
  return stack.map((font) => (/[\s\d]/.test(font) ? `"${font}"` : font)).join(", ");
}

function rgba(hex: string, alpha: number) {
  const value = Number.parseInt(hex.slice(1), 16);
  const rounded = Math.round(Math.min(alpha, 1) * 1000) / 1000;
  return `rgba(${(value >> 16) & 255}, ${(value >> 8) & 255}, ${value & 255}, ${rounded})`;
}

function entries<T extends object>(value: T) {
  return Object.entries(value) as [string, T[keyof T]][];
}

/** CSS `box-shadow` value of an elevation level for a tint and strength. */
export function elevationShadow(
  layers: readonly ShadowLayer[],
  tint: string,
  strength = 1,
  inset = false
) {
  if (layers.length === 0) return "none";
  return layers
    .map(
      (layer) =>
        `${inset ? "inset " : ""}${px(layer.x)} ${px(layer.y)} ${px(layer.blur)} ${px(layer.spread)} ${rgba(tint, layer.alpha * strength)}`
    )
    .join(", ");
}

/** Scale variables shared by every brand: spacing, sizes, type scale, motion, layers. */
export function foundationVariables(): Record<string, string> {
  const variables: Record<string, string> = {};
  const { spacing, radius, typography, sizing, borders, shadows, opacity, zIndex, motion } =
    primitives;

  for (const [key, value] of entries(spacing)) variables[spaceVariable(key)] = px(value);
  for (const [usage, steps] of entries(primitives.spaceUsages)) {
    for (const [size, step] of entries(steps)) {
      variables[`${cssPrefix}-${usage}-${size}`] = `var(${spaceVariable(step)})`;
    }
  }
  for (const [key, value] of entries(radius)) {
    variables[`${cssPrefix}-radius-${key}`] = key === "full" ? "9999px" : px(value);
  }
  for (const [key, value] of entries(typography.fontSize)) {
    variables[`${cssPrefix}-font-size-${key}`] = px(value);
  }
  for (const [key, value] of entries(typography.lineHeight)) {
    variables[`${cssPrefix}-line-height-${key}`] = px(value);
  }
  for (const [key, value] of entries(typography.leading)) {
    variables[`${cssPrefix}-leading-${key}`] = String(value);
  }
  for (const [key, value] of entries(typography.measure)) {
    variables[`${cssPrefix}-measure-${key}`] = `${value}ch`;
  }
  variables[`${cssPrefix}-underline-thickness`] = px(typography.underline.thickness);
  variables[`${cssPrefix}-underline-thickness-hover`] = px(typography.underline.hoverThickness);
  variables[`${cssPrefix}-underline-offset`] = px(typography.underline.offset);
  for (const [key, value] of entries(typography.fontWeight)) {
    variables[`${cssPrefix}-font-weight-${key}`] = value;
  }
  for (const [key, value] of entries(typography.letterSpacing)) {
    variables[`${cssPrefix}-tracking-${key}`] = value === 0 ? "0" : `${value}em`;
  }
  for (const [key, value] of entries(sizing.control)) {
    variables[`${cssPrefix}-control-height-${key}`] = px(value);
  }
  for (const [key, value] of entries(sizing.icon)) {
    variables[`${cssPrefix}-icon-size-${key}`] = px(value);
  }
  for (const [key, value] of entries(sizing.avatar)) {
    variables[`${cssPrefix}-avatar-size-${key}`] = px(value);
  }
  variables[`${cssPrefix}-touch-target`] = px(sizing.touchTarget);
  for (const [key, value] of entries(sizing.touchTargets)) {
    variables[`${cssPrefix}-touch-target-${key}`] = px(value);
  }
  for (const [key, value] of entries(sizing.container)) {
    variables[`${cssPrefix}-container-${key}`] = px(value);
  }
  for (const [key, value] of entries(sizing.dialog)) {
    variables[`${cssPrefix}-dialog-${key}`] = px(value);
  }
  for (const [key, value] of entries(sizing.floating)) {
    variables[`${cssPrefix}-${key}-max-width`] = px(value);
  }
  for (const [key, value] of entries(primitives.aspectRatios)) {
    variables[`${cssPrefix}-aspect-${key}`] = value;
  }
  const { chrome } = primitives;
  for (const [key, value] of entries(chrome.appBar)) {
    variables[`${cssPrefix}-app-bar-${key}`] = px(value);
  }
  variables[`${cssPrefix}-toolbar-height`] = px(chrome.toolbar);
  variables[`${cssPrefix}-bottom-bar-height`] = px(chrome.bottomBar);
  variables[`${cssPrefix}-tab-bar-height`] = px(chrome.tabBar);
  for (const [key, value] of entries(chrome.sidebar)) {
    variables[`${cssPrefix}-sidebar-${key}`] = px(value);
  }
  for (const [key, value] of entries(chrome.drawer)) {
    variables[`${cssPrefix}-drawer-${key}`] = px(value);
  }
  variables[`${cssPrefix}-aside-width`] = px(chrome.aside);
  for (const side of safeAreas) {
    variables[`${cssPrefix}-safe-${side}`] = `env(safe-area-inset-${side}, 0px)`;
  }
  Object.assign(variables, gridVariables("xs"));
  for (const [key, value] of entries(borders.width)) {
    variables[`${cssPrefix}-border-width-${key}`] = px(value);
  }
  variables[`${cssPrefix}-focus-ring-width`] = px(borders.focusRing.width);
  variables[`${cssPrefix}-focus-ring-offset`] = px(borders.focusRing.offset);
  for (const [key, shadow] of entries(shadows)) {
    variables[`${cssPrefix}-shadow-${key}`] =
      shadow.opacity === 0
        ? "none"
        : `${px(shadow.offsetX)} ${px(shadow.offsetY)} ${px(shadow.radius)} ${rgba(shadow.color, shadow.opacity)}`;
  }
  for (const [key, value] of entries(opacity)) {
    variables[`${cssPrefix}-opacity-${kebab(key)}`] = String(value);
  }
  for (const [step, value] of entries(primitives.alpha)) {
    variables[`${cssPrefix}-alpha-white-${step}`] = rgba("#ffffff", value);
    variables[`${cssPrefix}-alpha-black-${step}`] = rgba("#000000", value);
  }
  // State layers tint with the color of the element they are used on.
  for (const state of stateLayers) {
    variables[`${cssPrefix}-state-${state}`] =
      `color-mix(in srgb, currentColor ${Math.round(opacity[state] * 100)}%, transparent)`;
  }
  for (const [key, value] of entries(zIndex)) variables[`${cssPrefix}-z-${key}`] = String(value);
  for (const [key, value] of entries(motion.duration)) {
    variables[`${cssPrefix}-duration-${key}`] = `${value}ms`;
  }
  for (const [key, value] of entries(motion.easing)) {
    variables[`${cssPrefix}-easing-${kebab(key)}`] = value;
  }
  for (const [name, spring] of entries(motion.spring)) {
    const { samples, duration } = sampleSpring(spring);
    variables[`${cssPrefix}-spring-${name}`] = springEasing(samples);
    variables[`${cssPrefix}-spring-${name}-duration`] = `${duration}ms`;
  }
  for (const [name, transition] of entries(motion.transition)) {
    variables[`${cssPrefix}-transition-${name}`] =
      `var(${cssPrefix}-duration-${transition.duration}) var(${cssPrefix}-easing-${kebab(transition.easing)})`;
  }
  variables[`${cssPrefix}-stagger`] = `${motion.stagger}ms`;
  for (const [key, value] of entries(motion.distance)) {
    variables[`${cssPrefix}-motion-distance-${key}`] = px(value);
  }

  for (const [usage, level] of entries(primitives.elevationUsages)) {
    variables[`${cssPrefix}-elevation-${usage}`] = `var(${cssPrefix}-elevation-${level})`;
  }
  for (const [key, value] of entries(primitives.blur)) {
    variables[`${cssPrefix}-blur-${key}`] = px(value);
  }
  const { iconography, accessibility } = primitives;
  for (const [key, value] of entries(iconography.stroke)) {
    variables[`${cssPrefix}-icon-stroke-${key}`] = String(value);
  }
  variables[`${cssPrefix}-icon-gap`] = `${iconography.gap}em`;
  variables[`${cssPrefix}-target-spacing`] = px(accessibility.targetSpacing);
  variables[`${cssPrefix}-input-font-size`] = px(accessibility.inputFontSize);

  return variables;
}

/** Motion and density of a personality. Standard traits write nothing, so the scales apply. */
function personalityVariables(personality: Personality) {
  const variables: Record<string, string> = {};
  const preset = motionPresets[personality.motion];
  if (personality.motion !== "standard") {
    for (const [key, value] of entries(primitives.motion.duration)) {
      variables[`${cssPrefix}-duration-${key}`] = `${Math.round(value * preset.durationFactor)}ms`;
    }
    variables[`${cssPrefix}-easing-standard`] = preset.standard;
    variables[`${cssPrefix}-easing-emphasized`] = preset.emphasized;
    // Re-declared so they read the brand's durations and curves.
    for (const [name, transition] of entries(primitives.motion.transition)) {
      variables[`${cssPrefix}-transition-${name}`] =
        `var(${cssPrefix}-duration-${transition.duration}) var(${cssPrefix}-easing-${kebab(transition.easing)})`;
    }
  }
  if (personality.density !== "comfortable") {
    Object.assign(variables, densityVariables(primitives.density[personality.density]));
  }
  return variables;
}

/** A spring curve as a CSS `linear()` easing, about forty evenly spaced points. */
function springEasing(samples: readonly number[]) {
  const count = 40;
  const points = Array.from({ length: count + 1 }, (_, index) => {
    const value = samples[Math.round((index / count) * (samples.length - 1))];
    return String(Math.round(value * 1000) / 1000);
  });
  points[count] = "1";
  return `linear(${points.join(", ")})`;
}

/** Brand variables that do not change with the color mode: palettes, fonts, shapes, text styles. */
export function brandVariables(theme: BrandTheme): Record<string, string> {
  const variables: Record<string, string> = {};

  for (const [name, scale] of entries(theme.palette)) {
    for (const [step, value] of entries(scale)) {
      variables[`${cssPrefix}-palette-${name}-${step}`] = value;
    }
  }
  for (const [key, stack] of entries(theme.typography.fontFamily)) {
    variables[`${cssPrefix}-font-${key}`] = fontStack(stack);
  }
  for (const [usage, key] of entries(theme.shape)) {
    variables[`${cssPrefix}-radius-${usage}`] = `var(${cssPrefix}-radius-${key})`;
  }
  for (const [name, style] of entries(textStyles)) {
    const prefix = `${cssPrefix}-text-${name}`;
    const { fluid, leading } = style as TextStyle;
    variables[`${prefix}-family`] = `var(${cssPrefix}-font-${style.family})`;
    variables[`${prefix}-size`] = fluid
      ? fluidSize(fluid.min, style.size)
      : `var(${cssPrefix}-font-size-${style.size})`;
    variables[`${prefix}-line-height`] =
      fluid || leading
        ? `var(${cssPrefix}-leading-${fluid?.leading ?? leading})`
        : `var(${cssPrefix}-line-height-${style.size})`;
    const weight =
      style.category === "display" || style.category === "heading"
        ? shiftWeight(style.weight, headingShift[theme.personality.headings])
        : style.weight;
    variables[`${prefix}-weight`] = `var(${cssPrefix}-font-weight-${weight})`;
    variables[`${prefix}-tracking`] = `var(${cssPrefix}-tracking-${style.tracking})`;
  }

  for (const [name, gradient] of entries(gradients)) {
    const stops = gradient.stops.map((role) => `var(${cssColorVariable(role)})`).join(", ");
    variables[`${cssPrefix}-gradient-${kebab(name)}`] =
      `linear-gradient(${gradient.angle}deg, ${stops})`;
  }

  Object.assign(variables, personalityVariables(theme.personality));

  // Effects that read brand colors are declared with the brand, so a scoped identity gets its own.
  // A two-tone ring drawn with box-shadow: it follows the corner radius and survives
  // `overflow: hidden` on the parent.
  variables[`${cssPrefix}-focus-ring-shadow`] =
    `0 0 0 var(${cssPrefix}-focus-ring-offset) var(${cssColorVariable("surface")}), ` +
    `0 0 0 calc(var(${cssPrefix}-focus-ring-offset) + var(${cssPrefix}-focus-ring-width)) ` +
    `var(${cssColorVariable("focusRing")})`;
  // Halos per intent: `--ns-glow-md` in the primary color, `--ns-glow-danger-md` in danger...
  for (const intent of colorIntents) {
    for (const [key, glow] of entries(primitives.glows)) {
      const tint = (amount: number) =>
        `color-mix(in srgb, var(${cssColorVariable(intent)}) ${Math.round(amount * 100)}%, transparent)`;
      const name = intent === "primary" ? key : `${intent}-${key}`;
      variables[`${cssPrefix}-glow-${name}`] =
        `0 0 0 ${px(glow.spread)} ${tint(glow.alpha * 0.6)}, 0 ${px(glow.blur / 3)} ${px(glow.blur)} ${px(-glow.spread)} ${tint(glow.alpha)}`;
    }
  }

  const { depth } = primitives;
  for (const [key, value] of entries(depth.perspective)) {
    variables[`${cssPrefix}-perspective-${key}`] = px(value);
  }
  for (const [key, value] of entries(depth.layer)) {
    variables[`${cssPrefix}-depth-${key}`] = px(value);
  }
  for (const [key, value] of entries(depth.tilt)) {
    variables[`${cssPrefix}-tilt-${key}`] = `${value}deg`;
  }
  for (const [key, value] of entries(depth.interaction.parallax)) {
    variables[`${cssPrefix}-parallax-${key}`] = String(value);
  }
  for (const [key, value] of entries(depth.interaction.autoRotate)) {
    variables[`${cssPrefix}-auto-rotate-${key}`] = `${value}s`;
  }
  variables[`${cssPrefix}-float-amplitude`] = px(depth.float.amplitude);
  variables[`${cssPrefix}-float-period`] = `${depth.float.period}ms`;
  variables[`${cssPrefix}-contact-shadow`] =
    `0 ${px(depth.contactShadow.offset)} ${px(depth.contactShadow.blur)} rgba(0, 0, 0, ${depth.contactShadow.opacity})`;

  for (const [name, material] of entries(primitives.materials)) {
    variables[`${cssPrefix}-material-${name}`] =
      `color-mix(in srgb, var(${cssColorVariable("surface")}) ${Math.round(material.opacity * 100)}%, transparent)`;
    variables[`${cssPrefix}-material-${name}-filter`] =
      `blur(${px(material.blur)}) saturate(${material.saturate})`;
  }

  return variables;
}

export function colorVariables(colors: SemanticColors): Record<string, string> {
  return Object.fromEntries(
    semanticColorRoles.map((role) => [cssColorVariable(role), colors[role]])
  );
}

/** Chart and avatar colors of one mode. */
export function dataVariables(dataviz: DataVizColors, avatars: AvatarColors) {
  const variables: Record<string, string> = {};
  const scales = {
    cat: dataviz.categorical,
    seq: dataviz.sequential,
    div: dataviz.diverging
  };
  for (const [name, scale] of entries(scales)) {
    scale.forEach((color, index) => {
      variables[`${cssPrefix}-data-${name}-${index + 1}`] = color;
    });
  }
  variables[`${cssPrefix}-data-grid`] = dataviz.grid;
  variables[`${cssPrefix}-data-axis`] = dataviz.axis;
  avatars.forEach((pair, index) => {
    variables[`${cssPrefix}-avatar-${index + 1}-bg`] = pair.background;
    variables[`${cssPrefix}-avatar-${index + 1}-fg`] = pair.foreground;
  });
  return variables;
}

/** Every variable of a brand theme that changes with the color mode. */
function modeVariables(theme: BrandTheme, mode: ColorMode, highContrast = false) {
  const light = mode === "light";
  const tint = light ? theme.shadowTint.light : theme.shadowTint.dark;
  const strength = light ? 1 : darkShadowStrength;
  const { surface, surfaceRaised } = theme.colors[mode];
  return {
    ...colorVariables(highContrast ? theme.highContrast[mode] : theme.colors[mode]),
    ...dataVariables(theme.dataviz[mode], theme.avatars[mode]),
    ...elevationVariables(tint, strength),
    ...Object.fromEntries(
      entries(primitives.insetShadows).map(([key, layers]) => [
        `${cssPrefix}-shadow-inset-${key}`,
        elevationShadow(layers, tint, strength, true)
      ])
    ),
    // Surfaces lighten as they rise in dark mode; in light mode shadows do the work.
    ...Object.fromEntries(
      entries(primitives.darkSurfaceLift).map(([level, amount]) => [
        `${cssPrefix}-surface-level-${level}`,
        light ? (Number(level) === 0 ? surface : surfaceRaised) : mix(surface, "#ffffff", amount)
      ])
    )
  };
}

/**
 * Honors the user's system settings: reduced motion, reduced transparency, more contrast and
 * forced colors. `data-ns-motion`, `data-ns-transparency` and `data-ns-contrast` force a setting on
 * any element, for example from an in-app preference; `"full"`, `"normal"` opt back out.
 */
function preferenceBlocks() {
  const { duration, distance } = primitives.motion;
  const reducedMotion: Record<string, string> = {};
  for (const key of ["moderate", "slow", "slower", "slowest"] as const) {
    reducedMotion[`${cssPrefix}-duration-${key}`] = `${duration.fast}ms`;
  }
  for (const key of Object.keys(distance)) {
    reducedMotion[`${cssPrefix}-motion-distance-${key}`] = "0";
  }
  for (const name of Object.keys(primitives.motion.spring)) {
    reducedMotion[`${cssPrefix}-spring-${name}`] = primitives.motion.easing.standard;
    reducedMotion[`${cssPrefix}-spring-${name}-duration`] = `${duration.fast}ms`;
  }
  reducedMotion[`${cssPrefix}-easing-emphasized`] = primitives.motion.easing.standard;
  reducedMotion[`${cssPrefix}-stagger`] = "0ms";
  // Re-declared so they pick up the shorter durations where the setting is forced on an element.
  for (const [name, transition] of entries(primitives.motion.transition)) {
    reducedMotion[`${cssPrefix}-transition-${name}`] =
      `var(${cssPrefix}-duration-${transition.duration}) var(${cssPrefix}-easing-${kebab(transition.easing)})`;
  }

  const reducedTransparency: Record<string, string> = {};
  for (const name of Object.keys(primitives.materials)) {
    reducedTransparency[`${cssPrefix}-material-${name}`] = `var(${cssColorVariable("surface")})`;
    reducedTransparency[`${cssPrefix}-material-${name}-filter`] = "none";
  }

  const mixText = (amount: number) =>
    `color-mix(in srgb, var(${cssColorVariable("text")}) ${amount}%, var(${cssColorVariable("surface")}))`;
  const moreContrast = {
    [cssColorVariable("textMuted")]: mixText(88),
    [cssColorVariable("textSubtle")]: mixText(80),
    [cssColorVariable("textPlaceholder")]: mixText(80),
    [cssColorVariable("border")]: `var(${cssColorVariable("borderInput")})`,
    [cssColorVariable("borderSubtle")]: `var(${cssColorVariable("borderInput")})`,
    [cssColorVariable("borderStrong")]: `var(${cssColorVariable("borderInputHover")})`,
    [`${cssPrefix}-focus-ring-width`]: px(primitives.borders.focusRing.width + 1)
  };

  const preference = (
    media: string,
    attribute: string,
    on: string,
    off: string,
    variables: Record<string, string>
  ) => [
    `@media (${media}) {\n${block(`:root:not([${attribute}="${off}"])`, variables).replace(/^/gm, "  ")}\n}`,
    block(`[${attribute}="${on}"]`, variables)
  ];

  return [
    ...preference(
      "prefers-reduced-motion: reduce",
      "data-ns-motion",
      "reduce",
      "full",
      reducedMotion
    ),
    ...preference(
      "prefers-reduced-transparency: reduce",
      "data-ns-transparency",
      "reduce",
      "full",
      reducedTransparency
    ),
    ...preference("prefers-contrast: more", "data-ns-contrast", "more", "normal", moreContrast),
    `@media (forced-colors: active) {\n${block(":root", forcedColorVariables()).replace(/^/gm, "  ")}\n}`
  ];
}

/** System color of each role in Windows high contrast mode, so custom indicators stay visible. */
export function forcedColor(role: SemanticColorRole) {
  const exact: Partial<Record<SemanticColorRole, string>> = {
    textLinkVisited: "VisitedText",
    textLink: "LinkText",
    textLinkHover: "LinkText",
    highlight: "Mark",
    onHighlight: "MarkText",
    selection: "Highlight",
    onSelection: "HighlightText",
    surfaceSelected: "Highlight",
    focusRing: "Highlight",
    borderFocus: "Highlight",
    borderSelected: "Highlight",
    onTooltip: "CanvasText",
    overlay: "CanvasText"
  };
  if (exact[role]) return exact[role];
  if (role.endsWith("Disabled")) return "GrayText";
  if (role.startsWith("border") || role.endsWith("Border")) return "CanvasText";
  if (role.startsWith("text") || role.endsWith("Text")) return "CanvasText";
  if (role.startsWith("on")) return role.endsWith("Muted") ? "CanvasText" : "HighlightText";
  if (role.endsWith("Muted") || role.endsWith("MutedHover")) return "Canvas";
  if (role === "accent" || colorIntents.some((intent) => role.startsWith(intent))) {
    return "Highlight";
  }
  return "Canvas";
}

function forcedColorVariables() {
  return Object.fromEntries(
    semanticColorRoles.map((role) => [cssColorVariable(role), forcedColor(role)])
  );
}

/** Named animations built on the motion tokens; movement collapses to a fade with reduced motion. */
export const animations = {
  "fade-in": { from: "opacity: 0;", to: "", transition: "enter" },
  "fade-out": { from: "", to: "opacity: 0;", transition: "exit" },
  "scale-in": {
    from: "opacity: 0; transform: scale(0.96);",
    to: "",
    transition: "enter"
  },
  "slide-up": {
    from: `opacity: 0; transform: translateY(var(${cssPrefix}-motion-distance-lg));`,
    to: "",
    transition: "enter"
  },
  "slide-down": {
    from: `opacity: 0; transform: translateY(calc(var(${cssPrefix}-motion-distance-lg) * -1));`,
    to: "",
    transition: "enter"
  },
  shimmer: {
    from: "background-position: 200% 0;",
    to: "background-position: -200% 0;",
    transition: null
  },
  spin: { from: "transform: rotate(0deg);", to: "transform: rotate(360deg);", transition: null },
  pulse: { from: "opacity: 1;", to: "opacity: 0.5;", transition: null }
} as const;

export type AnimationName = keyof typeof animations;

/** CSS `animation` shorthand of a named animation. */
export function animationValue(name: AnimationName) {
  const { transition } = animations[name];
  if (transition) return `ns-${name} var(${cssPrefix}-transition-${transition}) both`;
  if (name === "spin") return "ns-spin 800ms linear infinite";
  if (name === "shimmer") return "ns-shimmer 1.6s linear infinite";
  return `ns-${name} 1s var(${cssPrefix}-easing-standard) infinite alternate`;
}

function animationRules() {
  return entries(animations).flatMap(([name, animation]) => {
    const keyframes = `@keyframes ns-${name} {\n  from {${animation.from ? ` ${animation.from} ` : ""}}\n  to {${animation.to ? ` ${animation.to} ` : ""}}\n}`;
    return [
      keyframes,
      `.ns-animate-${name} {\n  animation: ${animationValue(name as AnimationName)};\n}`
    ];
  });
}

